/* The 28-day calm co-parenting course (pitch/ux/course/curriculum.md) and the five seasonal modules that follow it.
   A day is a 1-minute lesson told as three cards (the real text, the calm way, the one idea to keep), then the
   pick-the-reply drill, then a "try it today" task. Everything here is static: no model call teaches a lesson.
   Their texts follow docs/VOICE.md (bursts, lowercase, shorthand); our replies sound like a decent adult on a phone.
   Education about communication only: not legal advice, not therapy, not a court-ordered parenting class. */
import type {Trigger as BankTrigger} from './drill-bank.js';

export interface LessonText {
  title: string;
  hook: string;              // card 1 headline; *word* is the one gradient word
  q: string;                 // the question under card 1
  from?: string;             // who sent it, when it isn't the other parent ("Emma, 8")
  them: string[];            // the burst
  jab?: number[];            // bubbles that are bait, struck through on card 2
  ask?: number;              // the bubble that needs an answer, outlined on card 2
  mine?: string;             // an earlier text of yours, still unanswered
  bad?: string;              // a draft that would feed it, crossed out on card 2
  calmHead: string;          // card 2 headline
  calm: string;              // the calm reply ('' when the calm way is not to reply)
  why: string;
  idea: string;              // card 3: the one line to keep
  try: string;               // "try it today"
  learned: [string, string, string];
}
export interface CourseDay extends LessonText { day: number; week: number }

