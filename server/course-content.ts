export function courseDay(day: number, topTrigger?: string): CourseDay {
  const d = COURSE[Math.min(Math.max(1, Math.floor(day)), COURSE_DAYS) - 1];
  const v = d.day === 1 && topTrigger ? DAY1[topTrigger] : undefined;
  return v ? {...d, ...v} : d;
}

/* ---------------- seasonal modules: five short courses after (or alongside) the 28 days ---------------- */

type Opt = [text: string, tag: string];
export interface ModuleQ { trigger: BankTrigger; them: string[]; good: 0 | 1 | 2; opts: [Opt, Opt, Opt]; jab?: number[]; ask?: number }
export interface ModuleDay {
  title: string; hook: string; calmHead: string; why: string; idea: string; try: string; learned: [string, string, string]; q: ModuleQ;
}
export interface CourseModule {
  id: 'holidays' | 'summer' | 'school' | 'partner' | 'mediation';
  title: string; sub: string; icon: string;
  triggers: BankTrigger[];
  /** Opens by the calendar: [month, day] from, to (inclusive, may wrap the new year). */
  window?: [[number, number], [number, number]];
  days: ModuleDay[];
}

