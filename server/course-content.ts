/** A module day as the player shows it: the same three cards as a course day, the module's own text on them. */
export function moduleLesson(m: CourseModule, n: number): LessonText {
  const d = m.days[Math.min(Math.max(1, n), m.days.length) - 1];
  const good = d.q.opts[d.q.good][0];
  return {title: d.title, hook: d.hook, q: 'What would you send?', them: d.q.them, jab: d.q.jab, ask: d.q.ask,
    calmHead: d.calmHead, calm: good.charAt(0).toUpperCase() + good.slice(1), why: d.why, idea: d.idea, try: d.try, learned: d.learned};
}

