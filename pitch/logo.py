import math
# Two rounded squares (side s, centred at 50,50), B rotated 45 deg. Straight edges cross at 8 points.
s, rx, sw = 66, 10, 5.6
h = s / 2
# Square A edges: x = 50±h, y = 50±h. Square B edges: lines at distance h from centre with normals at 45 deg.
pts = []
for ax in (1, -1):  # vertical edges of A: x = 50 + ax*h
    for sgn in (1, -1):
        # B edges: (x-50)*cos45 + (y-50)*sin45 = ±h  and  (x-50)*cos45 - (y-50)*sin45 = ±h
        for kind in (1, -1):
            x = ax * h
            # solve x*c + kind*y*c = sgn*h  -> y = (sgn*h - x*c)/(kind*c)
            c = math.cos(math.pi / 4)
            y = (sgn * h - x * c) / (kind * c)
            if abs(y) < h:
                pts.append((50 + x, 50 + y))
for ay in (1, -1):
    for sgn in (1, -1):
        for kind in (1, -1):
            y = ay * h
            c = math.cos(math.pi / 4)
            x = (sgn * h - kind * y * c) / c
            if abs(x) < h:
                pts.append((50 + x, 50 + y))
pts = sorted(set((round(x, 2), round(y, 2)) for x, y in pts), key=lambda p: math.atan2(p[1] - 50, p[0] - 50))
# alternate which square goes "under" at each crossing
cutA = pts[0::2]; cutB = pts[1::2]
r = sw * 1.15
def mask(id_, cuts):
    holes = ''.join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="#000"/>' for x, y in cuts)
    return f'<mask id="{id_}" maskUnits="userSpaceOnUse"><rect width="100" height="100" fill="#fff"/>{holes}</mask>'
def svg(color):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="none" stroke="{color}" stroke-width="{sw}">
  <!-- Parley mark (from the founder's Canva deck): two rounded squares, one turned 45 degrees, woven over and under. Generated by pitch/logo.py -->
  <defs>{mask('ma', cutA)}{mask('mb', cutB)}</defs>
  <rect x="{50-h}" y="{50-h}" width="{s}" height="{s}" rx="{rx}" mask="url(#ma)"/>
  <g mask="url(#mb)"><rect x="{50-h}" y="{50-h}" width="{s}" height="{s}" rx="{rx}" transform="rotate(45 50 50)"/></g>
</svg>
'''
import sys
open(sys.argv[1], 'w').write(svg('currentColor'))
open(sys.argv[2], 'w').write(svg('url(#g)').replace('<defs>', '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#9b84ff"/><stop offset=".5" stop-color="#5b6cf6"/><stop offset="1" stop-color="#3f8df5"/></linearGradient>'))
print(len(pts), pts)
